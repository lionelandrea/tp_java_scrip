// 1. Déclaration de variables
let num1 = 40;
let num2 = 20;

// 2. Opérations arithmétiques

console.log("Addition: " + (num1 + num2)); // Addition
console.log("Soustraction: " + (num1 - num2)); // Soustraction
console.log("Multiplication: " + (num1 * num2)); // Multiplication
console.log("Division: " + (num1 / num2)); // Division
console.log("Modulo: " + (num1 % num2)); // Modulo

//3. opérations de comparaison
console.log("num1 > num2", num1 > num2); // Supérieur à
console.log("num1 < num2", num1 < num2); // Inférieur à
console.log("num1 == num2", num1 == num2); // Égal à
console.log("num1 != num2", num1 != num2); // Différent de

//4.vDéclation des variables booléennes
let b1 = true;
let b2 = false;

//5. Opérations logiques
console.log("b1 && b2", b1 && b2); // ET logique
console.log("b1 || b2", b1 || b2); // OU logique
console.log("!b1", !b1); // NON logique
console.log("!b2", !b2); // NON logique